/** [{x, y}] for every filled cell of a glyph. */
export function glyphCells(glyph) {
  const cells = [];
  glyph.forEach((row, y) => {
    [...row].forEach((bit, x) => {
      if (bit === '1') cells.push({ x, y });
    });
  });
  return cells;
}